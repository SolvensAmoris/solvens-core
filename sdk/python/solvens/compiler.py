"""
COSMOS Language Compiler

Compiles .cosmos files to AST and vice versa.
"""

from typing import Optional
from pathlib import Path


class CosmosSyntaxError(Exception):
    """Raised when Cosmos syntax is invalid."""
    pass


def compile_cosmos(source: str) -> dict:
    """
    Compile Cosmos Language source to intermediate representation.
    
    Args:
        source: Cosmos Language source code
    
    Returns:
        Dict with providers, agents, tasks, and dags
    
    Raises:
        CosmosSyntaxError: If syntax is invalid
    """
    # Simple validation - in production, use proper parser
    result = {
        "providers": [],
        "agents": [],
        "tasks": [],
        "dags": [],
    }
    
    lines = source.strip().split("\n")
    current_block = None
    current_block_name = None
    current_block_content = {}
    
    for i, line in enumerate(lines, 1):
        line = line.strip()
        
        # Skip empty lines and comments
        if not line or line.startswith("#"):
            continue
        
        # Detect block starts
        if line.startswith("provider ") and "{" in line:
            current_block = "provider"
            current_block_name = line.split()[1]
            current_block_content = {}
            continue
        
        if line.startswith("agent ") and "{" in line:
            current_block = "agent"
            current_block_name = line.split()[1]
            current_block_content = {}
            continue
        
        if line.startswith("task ") and "{" in line:
            current_block = "task"
            current_block_name = line.split()[1]
            current_block_content = {}
            continue
        
        if line.startswith("dag ") and "{" in line:
            current_block = "dag"
            current_block_name = line.split()[1]
            current_block_content = {"edges": []}
            continue
        
        # Detect block end
        if line == "}":
            if current_block and current_block_name:
                entry = {"name": current_block_name, **current_block_content}
                
                if current_block == "provider":
                    result["providers"].append(entry)
                elif current_block == "agent":
                    result["agents"].append(entry)
                elif current_block == "task":
                    result["tasks"].append(entry)
                elif current_block == "dag":
                    result["dags"].append(entry)
            
            current_block = None
            current_block_name = None
            current_block_content = {}
            continue
        
        # Parse properties (handles both "key = value" and "key: value")
        if current_block and (":" in line or "=" in line):
            if ":" in line:
                key, value = line.split(":", 1)
            else:
                key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            
            # Handle arrays
            if value.startswith("["):
                items = value.strip("[]").split(",")
                value = [item.strip().strip('"').strip("'") for item in items]
            
            current_block_content[key] = value
            continue
        
        # Skip lines that are keyword references (e.g., "provider: openai" inside agent block)
        # These are not property assignments but references
        if current_block and any(kw in line for kw in ["provider", "agent", "task", "dag"]):
            continue
    
    return result


def decompile_cosmos(data: dict) -> str:
    """
    Convert intermediate representation back to Cosmos Language.
    
    Args:
        data: Dict with providers, agents, tasks, and dags
    
    Returns:
        Cosmos Language source code
    """
    lines = [
        "# Generated by SOLVENS SDK",
        "",
    ]
    
    # Providers
    for provider in data.get("providers", []):
        lines.append(f'provider {provider["name"]} {{')
        lines.append(f'  type: "{provider.get("type", provider["name"])}"')
        if "model" in provider:
            lines.append(f'  model: "{provider["model"]}"')
        lines.append("}")
        lines.append("")
    
    # Agents
    for agent in data.get("agents", []):
        lines.append(f'agent {agent["name"]} {{')
        if "provider" in agent:
            lines.append(f'  provider: {agent["provider"]}')
        if "system" in agent:
            lines.append(f'  system: "{agent["system"]}"')
        lines.append("}")
        lines.append("")
    
    # Tasks
    for task in data.get("tasks", []):
        lines.append(f'task {task["name"]} {{')
        if "agent" in task:
            lines.append(f'  agent: {task["agent"]}')
        if "provider" in task:
            lines.append(f'  provider: "{task["provider"]}"')
        if "depends_on" in task:
            deps = task["depends_on"]
            if isinstance(deps, list):
                deps_str = ", ".join(deps)
            else:
                deps_str = deps
            lines.append(f'  depends_on: [{deps_str}]')
        if "retry" in task:
            lines.append(f'  retry: {task["retry"]}')
        if "timeout" in task:
            lines.append(f'  timeout: {task["timeout"]}')
        lines.append("}")
        lines.append("")
    
    # DAGs
    for dag in data.get("dags", []):
        lines.append(f'dag {dag["name"]} {{')
        if "tasks" in dag:
            lines.append(f'  tasks: [{", ".join(dag["tasks"])}]')
        for edge in dag.get("edges", []):
            lines.append(f'  {edge["from"]} -> {edge["to"]}')
        lines.append("}")
        lines.append("")
    
    return "\n".join(lines)


def load_cosmos_file(path: str | Path) -> dict:
    """
    Load and compile a .cosmos file.
    
    Args:
        path: Path to .cosmos file
    
    Returns:
        Dict with compiled workflow
    """
    path = Path(path)
    
    if not path.exists():
        raise FileNotFoundError(f"File not found: {path}")
    
    source = path.read_text()
    return compile_cosmos(source)


def save_cosmos_file(data: dict, path: str | Path) -> None:
    """
    Save workflow as a .cosmos file.
    
    Args:
        data: Workflow data
        path: Output path
    """
    path = Path(path)
    source = decompile_cosmos(data)
    path.write_text(source)
