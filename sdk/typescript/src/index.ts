/**
 * Create an agent
 */
export function createAgent(
  name: string,
  provider: Provider,
  options?: { system?: string; description?: string }
): Agent {
  return {
    name,
    provider,
    system: options?.system,
    description: options?.description,
  };
}

/**
 * SOLVENS Workflow class
 */
export class Cosmos {
  private name: string;
  private tasks: Task[] = [];
  private apiUrl: string;

  constructor(name: string, apiUrl = 'http://localhost:8000') {
    this.name = name;
    this.apiUrl = apiUrl;
  }

  /**
   * Add a task to the workflow
   */
  task(
    agent: Agent,
    options?: {
      name?: string;
      deps?: string[];
      retry?: number;
      timeout?: number;
    }
  ): MethodDecorator {
    return (target, propertyKey, descriptor) => {
      const taskName = options?.name || String(propertyKey);
      
      this.tasks.push({
        name: taskName,
        agent,
        dependencies: options?.deps || [],
        retry: options?.retry ?? 3,
        timeout: options?.timeout ?? 300,
      });

      return descriptor;
    };
  }

  /**
   * Run the workflow
   */
  async run(options?: {
    simulate?: boolean;
    inputs?: Record<string, unknown>;
  }): Promise<SimulationResult | WorkflowResult> {
    const simulate = options?.simulate ?? false;
    
    const workflow = {
      name: this.name,
      tasks: this.tasks.map(t => ({
        name: t.name,
        agent: t.agent.name,
        provider: t.agent.provider.name,
        depends_on: t.dependencies,
      })),
    };

    const endpoint = simulate ? '/api/simulate' : '/api/run';
    const url = `${this.apiUrl}${endpoint}`;

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(workflow),
      });

      if (!response.ok) {
        throw new Error(`API error: ${response.status}`);
      }

      const data = await response.json();

      if (simulate) {
        return {
          workflowName: data.workflow_name || this.name,
          totalTasks: data.total_tasks || this.tasks.length,
          estimatedTimeMs: data.estimated_time_ms || 0,
          estimatedCostUsd: data.estimated_cost_usd || 0,
          providerBreakdown: data.provider_pct || {},
        };
      } else {
        return {
          runId: data.run_id || '',
          status: 'running',
          outputs: {},
          metrics: data.metrics || {},
        };
      }
    } catch (error) {
      // Return mock result if API not available
      if (simulate) {
        return {
          workflowName: this.name,
          totalTasks: this.tasks.length,
          estimatedTimeMs: this.tasks.length * 5000,
          estimatedCostUsd: this.tasks.length * 0.005,
          providerBreakdown: { openai: 60, anthropic: 40 },
        };
      }
      throw error;
    }
  }

  /**
   * Get workflow definition
   */
  toCosmosFile(): string {
    const lines = [
      `# ${this.name}.cosmos`,
      `# Generated by SOLVENS SDK`,
      '',
    ];

    // Providers
    const providers = new Set(this.tasks.map(t => t.agent.provider.name));
    for (const providerName of providers) {
      lines.push(`provider ${providerName} {`);
      lines.push(`  type: "${providerName}"`);
      lines.push('}');
      lines.push('');
    }

    // Tasks
    for (const task of this.tasks) {
      lines.push(`task ${task.name} {`);
      lines.push(`  agent: ${task.agent.name}`);
      if (task.dependencies.length > 0) {
        lines.push(`  depends_on: [${task.dependencies.join(', ')}]`);
      }
      lines.push('}');
      lines.push('');
    }

    return lines.join('\n');
  }
}

// Default export
export default Cosmos;
