@app.command()
def doctor():
    """Check system configuration and dependencies."""
    from cosmos.providers.llm import llm
    
    console.print(Panel.fit(
        "[cyan]SOLVENS Doctor[/cyan]\n"
        "Checking configuration...",
        border_style="cyan"
    ))
    
    table = Table(title="Configuration Check")
    table.add_column("Component", style="cyan")
    table.add_column("Status", style="yellow")
    table.add_column("Details", style="dim")
    
    # Check Python
    python_version = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    table.add_row("Python", "✓", python_version)
    
    # Check providers
    available_providers = llm.list_providers()
    if available_providers:
        table.add_row("LLM Providers", "✓", ", ".join(p.value for p in available_providers))
    else:
        table.add_row("LLM Providers", "⚠", "No providers configured")
    
    # Check API keys
    has_anthropic = bool(os.getenv("ANTHROPIC_API_KEY"))
    has_openai = bool(os.getenv("OPENAI_API_KEY"))
    
    if has_anthropic:
        table.add_row("ANTHROPIC_API_KEY", "✓", "Configured")
    else:
        table.add_row("ANTHROPIC_API_KEY", "⚠", "Not set")
    
    if has_openai:
        table.add_row("OPENAI_API_KEY", "✓", "Configured")
    else:
        table.add_row("OPENAI_API_KEY", "⚠", "Not set")
    
    # Check Ollama
    try:
        import httpx
        response = httpx.get("http://localhost:11434/api/tags", timeout=2)
        if response.status_code == 200:
            table.add_row("Ollama", "✓", "Running locally")
        else:
            table.add_row("Ollama", "⚠", "Not responding")
    except:
        table.add_row("Ollama", "⚠", "Not running")
    
    console.print(table)
    
    print_info("Run 'solvens init' to create a new project")


