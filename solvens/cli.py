@app.command()
def init(
    name: str = typer.Option("my-workflow", help="Workflow name"),
    path: Path = typer.Option(".", help="Project directory"),
):
    """Initialize a new SOLVENS project."""
    project_dir = path / name
    
    if project_dir.exists():
        print_error(f"Directory '{project_dir}' already exists")
        raise typer.Exit(1)
    
    project_dir.mkdir(parents=True)
    
    # Create basic workflow
    workflow_content = f'''# {name}.cosmos
# Generated by SOLVENS

provider claude {{
  type = "anthropic"
  model = "claude-3-5-sonnet"
}}

task hello_world {{
  provider = "claude"
  depends_on = []
}}

task goodbye {{
  provider = "claude"
  depends_on = [hello_world]
}}
'''
    
    (project_dir / f"{name}.cosmos").write_text(workflow_content)
    
    # Create config
    config_content = '''# SOLVENS Configuration
# Copy to .env and fill in your API keys

# Providers
ANTHROPIC_API_KEY=your-key-here
OPENAI_API_KEY=your-key-here

# Ollama (optional, for local inference)
OLLAMA_BASE_URL=http://localhost:11434

# Cost Limits
MAX_COST_PER_RUN=1.00
MAX_DAILY_COST=100.00
'''
    (project_dir / ".env.example").write_text(config_content)
    
    # Create README
    readme_content = f'''# {name}

A SOLVENS workflow project.

## Usage

```bash
solvens compile {name}.cosmos
solvens validate {name}.cosmos
solvens simulate {name}.cosmos
solvens run {name}.cosmos
```
'''
    (project_dir / "README.md").write_text(readme_content)
    
    print_success(f"Initialized project at {project_dir}")
    print_info("Copy .env.example to .env and add your API keys")


