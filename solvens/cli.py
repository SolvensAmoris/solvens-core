@app.command()
def compile(
    file: Path = typer.Argument(..., help="Workflow file (.cosmos)"),
    strict: bool = typer.Option(False, help="Enable strict validation"),
    json_output: bool = typer.Option(False, help="Output JSON"),
):
    """Compile a Cosmos workflow file."""
    from cosmos.parser.parser import Parser
    
    if not file.exists():
        print_error(f"File not found: {file}")
        raise typer.Exit(1)
    
    try:
        content = file.read_text()
        parser = Parser(content)
        ast = parser.parse()
        
        if not json_output:
            console.print(Panel.fit(
                f"[green]Compiled successfully[/green]\n"
                f"File: {file.name}\n"
                f"Statements: {len(ast.statements)}",
                border_style="green"
            ))
            
            # Show summary
            table = Table(title="Workflow Summary")
            table.add_column("Element", style="cyan")
            table.add_column("Count", style="yellow")
            
            providers = sum(1 for s in ast.statements if hasattr(s, 'properties'))
            # Simple count (actual impl would traverse AST)
            table.add_row("Providers", str(providers))
            table.add_row("Statements", str(len(ast.statements)))
            
            console.print(table)
        else:
            rprint(json.dumps({
                "status": "success",
                "file": str(file),
                "statements": len(ast.statements),
            }))
        
        print_success("Compilation successful")
        
    except Exception as e:
        print_error(f"Compilation failed: {e}")
        raise typer.Exit(1)


