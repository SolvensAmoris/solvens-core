#!/usr/bin/env python3
"""
SOLVENS Meta Builder CLI

Build workflows from natural language prompts.

Usage:
    python -m meta.cli "build me a CRM for dentists with billing"
    python -m meta.cli --interactive
    python -m meta.cli --template "saas-starter"
"""

import argparse
import sys
import json
import re
from typing import Optional


class CosmosBuilder:
    """Generate Cosmos Language files from prompts."""
    
    def __init__(self):
        self.providers = {
            "claude": {"type": "anthropic", "model": "claude-3-5-sonnet"},
            "openai": {"type": "openai", "model": "gpt-4o"},
            "ollama": {"type": "ollama", "model": "llama3"},
        }
    
    def build(self, prompt: str) -> str:
        """Build a .cosmos file from a prompt."""
        
        # Detect features from prompt
        features = self._detect_features(prompt)
        
        # Generate providers
        providers = self._generate_providers(features)
        
        # Generate agents
        agents = self._generate_agents(features)
        
        # Generate tasks
        tasks = self._generate_tasks(features)
        
        # Combine
        lines = [
            f"# Generated by SOLVENS Meta Builder",
            f"# Prompt: {prompt}",
            f"",
        ]
        
        lines.extend(providers)
        lines.append("")
        lines.extend(agents)
        lines.append("")
        lines.extend(tasks)
        
        return "\n".join(lines)
    
    def _detect_features(self, prompt: str) -> dict:
        """Detect required features from prompt."""
        lower = prompt.lower()
        
        features = {
            "auth": any(w in lower for w in ["auth", "login", "user", "signup"]),
            "database": any(w in lower for w in ["db", "database", "data", "sql"]),
            "api": any(w in lower for w in ["api", "rest", "endpoint"]),
            "frontend": any(w in lower for w in ["ui", "frontend", "web", "dashboard"]),
            "billing": any(w in lower for w in ["billing", "payment", "invoice", "subscription", "stripe"]),
            "notifications": any(w in lower for w in ["notification", "email", "slack", "sms"]),
            "analytics": any(w in lower for w in ["analytics", "dashboard", "metrics", "report"]),
            "testing": True,  # Always include tests
            "deploy": True,   # Always include deploy
        }
        
        return features
    
    def _generate_providers(self, features: dict) -> list:
        lines = []
        
        # Always include Claude for reasoning
        lines.append('provider claude {')
        lines.append('  type: "anthropic"')
        lines.append('  model: "claude-3-5-sonnet"')
        lines.append("}")
        
        # Include OpenAI for code gen
        if features.get("frontend") or features.get("api"):
            lines.append("")
            lines.append('provider openai {')
            lines.append('  type: "openai"')
            lines.append('  model: "gpt-4o"')
            lines.append("}")
        
        # Include Ollama for local/free tasks
        lines.append("")
        lines.append('provider ollama {')
        lines.append('  type: "ollama"')
        lines.append('  model: "llama3"')
        lines.append("}")
        
        return lines
    
    def _generate_agents(self, features: dict) -> list:
        lines = []
        
        lines.append('agent architect {')
        lines.append('  provider: claude')
        lines.append('  system: "You are a software architect designing scalable systems."')
        lines.append("}")
        
        if features.get("frontend") or features.get("api"):
            lines.append("")
            lines.append('agent coder {')
            lines.append('  provider: openai')
            lines.append('  system: "You are an expert fullstack developer."')
            lines.append("}")
        
        lines.append("")
        lines.append('agent tester {')
        lines.append('  provider: ollama')
        lines.append('  system: "You write comprehensive tests."')
        lines.append("}")
        
        return lines
    
    def _generate_tasks(self, features: dict) -> list:
        tasks = []
        lines = []
        
        # Core tasks
        tasks.append(("design_system", ["architect"], []))
        tasks.append(("setup_infra", ["architect"], ["design_system"]))
        
        if features.get("database"):
            tasks.append(("design_database", ["architect"], ["design_system"]))
            tasks.append(("implement_database", ["coder"], ["design_database"]))
        
        if features.get("api"):
            tasks.append(("design_api", ["architect"], ["design_system"]))
            tasks.append(("implement_api", ["coder"], ["design_api"]))
        
        if features.get("auth"):
            tasks.append(("implement_auth", ["coder"], ["design_api"]))
        
        if features.get("billing"):
            tasks.append(("implement_billing", ["coder"], ["design_api", "implement_auth"]))
        
        if features.get("frontend"):
            tasks.append(("design_ui", ["architect"], ["design_api"]))
            tasks.append(("implement_frontend", ["coder"], ["design_ui"]))
        
        if features.get("analytics"):
            tasks.append(("implement_analytics", ["coder"], ["design_api"]))
        
        if features.get("notifications"):
            tasks.append(("implement_notifications", ["coder"], ["design_api"]))
        
        # Always include testing and deploy
        depends = []
        if features.get("implement_api"):
            depends.append("implement_api")
        if features.get("implement_frontend"):
            depends.append("implement_frontend")
        if features.get("implement_database"):
            depends.append("implement_database")
        
        tasks.append(("write_tests", ["tester"], depends if depends else ["design_system"]))
        tasks.append(("deploy", ["architect"], ["write_tests"]))
        
        for task_name, agent, deps in tasks:
            lines.append(f"task {task_name} {{")
            lines.append(f"  agent: {agent[0]}")
            if deps:
                lines.append(f"  depends_on: [{', '.join(deps)}]")
            lines.append("}")
            lines.append("")
        
        return lines


def main():
    parser = argparse.ArgumentParser(
        description="SOLVENS Meta Builder - Generate workflows from prompts"
    )
    parser.add_argument("prompt", nargs="?", help="Natural language prompt")
    parser.add_argument("--interactive", "-i", action="store_true", help="Interactive mode")
    parser.add_argument("--output", "-o", help="Output file")
    parser.add_argument("--template", "-t", help="Use template instead of prompt")
    
    args = parser.parse_args()
    
    if args.template:
        templates = {
            "saas-starter": "build a SaaS with auth, database, API, frontend, and billing",
            "data-pipeline": "build an ETL pipeline with data validation, transformation, and storage",
            "agent-swarm": "build 10 AI agents that collaborate on complex tasks",
            "api-gateway": "build an API gateway with rate limiting, auth, and logging",
        }
        prompt = templates.get(args.template, args.template)
    elif args.interactive:
        print("SOLVENS Meta Builder - Interactive Mode")
        print("=" * 40)
        prompt = input("What do you want to build? ")
    else:
        prompt = args.prompt
    
    if not prompt:
        parser.print_help()
        sys.exit(1)
    
    builder = CosmosBuilder()
    cosmos_content = builder.build(prompt)
    
    if args.output:
        with open(args.output, "w") as f:
            f.write(cosmos_content)
        print(f"✓ Generated: {args.output}")
    else:
        print("\n" + cosmos_content + "\n")
    
    print("""
To run this workflow:
    solvens run output.cosmos
    
To simulate:
    solvens simulate output.cosmos
""")


if __name__ == "__main__":
    main()
